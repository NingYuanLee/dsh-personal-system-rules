import { transform } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';

// Keep the source readable while emitting the same CommonJS loader envelope
// used by dsh-grok-byapi. The Harness web boot loader expects this envelope.
let source = await readFile(new URL('../client-src.js', import.meta.url), 'utf8');
source = source.replace(/^import React[^\n]*\n/, "const React = require('react');\n");
source = source.replace(/window\.__ModuleLoader__\.load\(\{\s*id:\s*'dsh-personal-system-rules',\s*factory\(require\)\s*\{/, '');
source = source.replace(/\n\s*return \{\s*\n\s*inject:/, '\n    module.exports = {\n      inject:');
source = source.replace(/\n\s*\}\s*\n\s*\}\s*,\s*\}\)\s*;?\s*$/, '\n    }');

const result = await transform(source, {
  format: 'cjs',
  target: 'es2022',
  platform: 'browser',
});
const built = `// Generated by npm run build. Do not edit.
window.__ModuleLoader__.load({id: "dsh-personal-system-rules", factory: (require) => {
const module = {exports: {}}; const exports = module.exports;
${result.code}
return module.exports;
}});`;
await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
await writeFile(new URL('../client.js', import.meta.url), built);
